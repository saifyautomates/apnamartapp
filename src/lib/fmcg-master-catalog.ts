/** Lookup a barcode in the FMCG Master Database or heuristically predict details */
export function lookupMasterFmcgBarcode(barcode: string): MasterCatalogItem {
  const clean = barcode.trim();
  if (FMCG_MASTER_DATABASE[clean]) {
    return FMCG_MASTER_DATABASE[clean];
  }

  // Heuristic prefix match
  for (const b of FMCG_BRAND_PREFIXES) {
    if (clean.startsWith(b.prefix)) {
      return {
        barcode: clean,
        name: `${b.brand} FMCG Grocery Item (${clean.slice(-4)})`,
        brand: b.brand,
        categorySlug: b.categorySlug,
        categoryName: b.categoryName,
        packSize: "Standard Pack",
        mrpPaise: 10000, // ₹100 default
        suggestedSellingPaise: 9200, // ₹92
        hsnSac: "21069099",
        gstBps: 1200,
        unit: "pack",
        description: `Premium ${b.brand} product scanned via barcode scanner.`,
      };
    }
  }

  // Fallback for general grocery barcode
  return {
    barcode: clean,
    name: `FMCG Product (${clean})`,
    brand: "Central Mart Select",
    categorySlug: "staples",
    categoryName: "Atta, Rice & Dal",
    packSize: "1 Unit",
    mrpPaise: 5000, // ₹50
    suggestedSellingPaise: 4500, // ₹45
    hsnSac: "21069099",
    gstBps: 500,
    unit: "pack",
    description: `Grocery product with barcode ${clean}. Ready to sell.`,
  };
}
